import { _electron as electron } from "playwright";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { strict as assert } from "node:assert";
const root = path.resolve(import.meta.dirname, "..");
const data = await fs.mkdtemp(path.join(os.tmpdir(), "zhixing-interactions-ui-"));
let app;
try {
  app = await electron.launch({ ...(process.env.ZHIXING_DESKTOP_EXECUTABLE ? { executablePath: process.env.ZHIXING_DESKTOP_EXECUTABLE } : {}), args: process.env.ZHIXING_DESKTOP_EXECUTABLE && !process.env.ZHIXING_DESKTOP_DEV ? [] : [root], env: { ...process.env, ZHIXING_DESKTOP_TEST_DATA: data, ZHIXING_ALLOW_LIVE_PROVIDER: "0", PI_CODING_AGENT_DIR: path.join(data, "pi-empty") }, timeout: 30000 });
  const page = await app.firstWindow(); page.setDefaultTimeout(20000);
  await page.getByRole("button", { name: "发送消息", exact: true }).waitFor();
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  const state = await page.evaluate(async () => {
    const invoke = async (command) => { const result = await window.zhixing.invoke(command); if (!result.ok) throw new Error(result.error); return result.data; };
    const boot = await invoke({ type: "boot" });
    await invoke({ type: "settings", settings: { ...boot.settings, provider: "demo" } });
    await invoke({ type: "learning-action", topicId: "agent-development", command: "开始第 1 天" });
    return { boot, session: await invoke({ type: "new" }) };
  });
  const session = state.session; const now = new Date().toISOString();
  session.topicId = "agent-development"; session.workspaceId = state.boot.workspace.id; session.contextAllowed = true;
  session.messages = [{ id: randomUUID(), role: "user", text: "完成一个示例", status: "completed", createdAt: now }, { id: randomUUID(), role: "assistant", text: "", status: "waiting", provider: "demo", taskId: randomUUID(), createdAt: now, items: [{ id: randomUUID(), kind: "approval", title: "保存示例产物", status: "pending", tool: "save_artifact", input: { dayId: "D01", kind: "implementation", text: "export const result = 42;" } }, { id: randomUUID(), kind: "question", title: "下一步学习方向", status: "pending", options: ["讲解代码", "测试边界"] }] }];
  await fs.writeFile(path.join(data, "conversations", `${session.id}.json`), JSON.stringify(session));
  await page.evaluate((id) => localStorage.setItem("last-session", id), session.id); await page.reload();
  await page.getByRole("button", { name: "允许这一次", exact: true }).click();
  await page.getByText("已处理：允许", { exact: true }).waitFor();
  await page.getByRole("button", { name: "停止生成", exact: true }).waitFor({ state: "hidden" });
  await page.getByText("已保存 · D01 · implementation", { exact: true }).waitFor();
  await page.getByRole("button", { name: "讲解代码", exact: true }).click();
  await page.getByText("已处理：讲解代码", { exact: true }).waitFor();
  await page.getByRole("button", { name: "停止生成", exact: true }).waitFor({ state: "hidden" });
  const evidence = await page.evaluate(async () => (await window.zhixing.invoke({ type: "evidence-list", topicId: "agent-development", dayId: "D01" })).data);
  assert.equal(evidence.artifacts.length, 1);
  await page.getByRole("button", { name: "编辑并重发", exact: true }).first().click();
  await page.getByRole("textbox", { name: "编辑消息", exact: true }).fill("改用另一种解释");
  await page.getByRole("button", { name: "发送为新分支", exact: true }).click();
  await page.locator(".user-bubble").getByText("改用另一种解释", { exact: true }).waitFor();
  await page.getByRole("button", { name: "停止生成", exact: true }).waitFor({ state: "hidden" });
  assert.equal(await page.getByRole("checkbox", { name: /本会话使用学习上下文/ }).isChecked(), false);
  await page.getByRole("button", { name: "对比回答", exact: true }).click();
  await page.getByRole("dialog", { name: "对比回答", exact: true }).waitFor();
  assert.equal(await page.getByRole("combobox", { name: "左侧回答", exact: true }).locator("option").count(), 3);
  await page.getByRole("button", { name: "关闭对比", exact: true }).click();
  await page.getByRole("combobox", { name: "学习主题", exact: true }).selectOption("agent-development");
  await page.getByRole("button", { name: "课程与资料", exact: true }).click();
  const skill = page.getByRole("combobox", { name: "学习技能", exact: true });
  await skill.locator("option").nth(1).waitFor({ state: "attached" });
  await skill.selectOption({ index: 1 });
  await page.getByRole("button", { name: "使用这个技能", exact: true }).click();
  assert.match(await page.getByRole("textbox", { name: "发送给知行", exact: true }).inputValue(), /学习技能/);
  await page.getByRole("button", { name: "设置", exact: true }).click();
  const exportParent = path.join(data, "exports"); await fs.mkdir(exportParent);
  await app.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, exportParent);
  await page.getByRole("button", { name: "备份全部学习数据", exact: true }).click();
  await page.getByText(/备份已保存：/).waitFor();
  const backup = path.join(exportParent, (await fs.readdir(exportParent))[0]);
  const manifest = JSON.parse(await fs.readFile(path.join(backup, "manifest.json"), "utf8"));
  assert.ok(manifest.files.some((item) => item.path.endsWith("zhixing.sqlite")));
  await app.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false }); }, backup);
  await page.getByRole("button", { name: "从备份恢复", exact: true }).click();
  await page.getByText(/已恢复 .* 段对话，新工作区：/).waitFor();
  const restored = await page.evaluate(async () => (await window.zhixing.invoke({ type: "boot" })).data);
  assert.notEqual(restored.workspace.id, state.boot.workspace.id);
  assert.ok(restored.sessions.some((item) => item.title.endsWith("· 恢复")));
  const restoredEvidence = await page.evaluate(async () => (await window.zhixing.invoke({ type: "evidence-list", topicId: "agent-development", dayId: "D01" })).data);
  assert.equal(restoredEvidence.artifacts.length, 1);
  assert.deepEqual(errors, []);
  console.log("Interactions UI passed: concrete approval, exact-once artifact, question reply, edit-and-fork, reset permissions and comparison with the parent conversation, skill preview, full backup and non-destructive restore.");
} finally { await app?.close(); await fs.rm(data, { recursive: true, force: true }); }
